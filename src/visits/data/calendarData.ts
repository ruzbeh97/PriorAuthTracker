import type { ReadinessState } from "../types/prototype";

/**
 * Day view: one column per provider. Rows are 30-minute slots starting at 7:00 AM,
 * so row 1 = 7:00, row 3 = 8:00, and so on through 2:00 PM.
 */
export interface CalendarColumn {
  provider: string;
  appointmentCount: number;
  /** Hatched "Not Available" block covering rows 1 through this row, inclusive. */
  unavailableUntilRow: number;
}

export type CardVariant =
  | "muted"
  | "blue"
  | "solid"
  | "red"
  | "pink"
  | "magenta"
  | "yellow"
  | "outline"
  | "plain";

export interface CalendarAppointment {
  patient: string;
  time?: string;
  caseName: string;
  type: string;
  status: string;
  location?: string;
  /** Half-width cards sit side by side in one slot and show the facility instead of a status. */
  half?: "left" | "right";
  facility?: string;
  /** Blue tick beside the name, marking a confirmed arrival. */
  verified?: boolean;
  day: number;
  startRow: number;
  span: number;
  variant: CardVariant;
  interactive?: boolean;
  readiness?: ReadinessState;
}

